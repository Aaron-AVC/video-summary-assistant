import { fetchTranscriptDom } from "@/features/transcript/lib/fetch-transcript-dom"
import { fetchTranscriptPanel } from "@/features/transcript/lib/fetch-transcript-panel"
import { fetchVtt } from "@/features/transcript/lib/fetch-vtt"
import { normalizeCues } from "@/features/transcript/lib/normalize-cues"
import { parseVtt } from "@/features/transcript/lib/parse-vtt"
import {
  TranscriptUnsupportedError,
  type FetchVttFailure,
  type FetchVttResult,
  type FetchVttSuccess,
} from "@/features/transcript/lib/transcript-schema"
import { createLogCollector } from "@/features/transcript/lib/transcript-log"
import { readPageMetadata } from "@/features/youtube/lib/read-page-metadata"
import { isSupportedYouTubeWatchUrl } from "@/features/platform/youtube/youtube-url"
import type {
  PlatformPageEnvironment,
  VideoPlatformAdapter,
} from "@/features/platform/adapter"
import type {
  TranscriptSource,
  VideoIdentity,
  VideoInfo,
  VideoTranscript,
} from "@/features/platform/types"

export const youtubeAdapter: VideoPlatformAdapter = {
  platform: "youtube",

  canHandle(url) {
    return this.getVideoIdentity(url) !== null
  },

  getVideoIdentity(url) {
    if (!isSupportedYouTubeWatchUrl(url)) {
      return null
    }

    const videoId = url.searchParams.get("v")?.trim()
    if (!videoId) {
      return null
    }

    return {
      platform: "youtube",
      videoId,
      contentKey: `youtube:${videoId}`,
    }
  },

  readVideoInfo(env) {
    const identity = requireIdentity(env.location)
    const metadata = readPageMetadata(
      env.location.href,
      env.document.documentElement.outerHTML,
    )
    const title =
      readText(env.document, "ytd-watch-metadata h1")
      ?? readText(env.document, "h1.ytd-watch-metadata")
      ?? normalizeDocumentTitle(env.document.title)
      ?? metadata.title
      ?? identity.videoId
    const video = env.document.querySelector<HTMLVideoElement>("video")

    return {
      ...identity,
      title,
      author:
        readText(env.document, "#owner a.yt-simple-endpoint")
        ?? readText(env.document, "ytd-channel-name a")
        ?? null,
      durationSec: Number.isFinite(video?.duration) ? video!.duration : null,
      thumbnailUrl: `https://i.ytimg.com/vi/${identity.videoId}/hqdefault.jpg`,
      canonicalUrl: buildCanonicalUrl(identity.videoId),
    }
  },

  async getTranscript(env) {
    const identity = requireIdentity(env.location)
    const html = env.document.documentElement.outerHTML
    const pageUrl = env.location.href
    const metadata = readPageMetadata(pageUrl, html)
    const collector = env.diagnosticLoggingEnabled
      ? createLogCollector(identity.videoId, pageUrl)
      : null

    const timedtext = await runTranscriptStep({
      stepName: "fetchVtt",
      run: () => fetchVtt({ tracks: metadata.tracks, fetchImpl: env.fetch }),
      collector,
      details: `${metadata.tracks.length} track(s) found`,
    })

    if (timedtext.ok) {
      collector?.finalize("success", "fetchVtt")
      return normalizeTranscript(timedtext, timedtext.track.isAutoGenerated ? "auto" : "manual")
    }

    const panel = await runTranscriptStep({
      stepName: "fetchTranscriptPanel",
      run: () => fetchTranscriptPanel({ metadata, pageUrl, fetchImpl: env.fetch }),
      collector,
      details: metadata.transcriptPanel ? "panel bootstrap available" : "no panel bootstrap",
    })

    if (panel?.ok) {
      collector?.finalize("success", "fetchTranscriptPanel")
      return normalizeTranscript(panel, "unknown")
    }

    const renderedDom = await runTranscriptStep({
      stepName: "fetchTranscriptDom",
      run: () => fetchTranscriptDom({ document: env.document, metadata, videoId: identity.videoId }),
      collector,
    })

    if (renderedDom.ok) {
      collector?.finalize("success", "fetchTranscriptDom")
      return normalizeTranscript(renderedDom, "unknown")
    }

    const errors: string[] = []
    if (timedtext.ok === false) {
      errors.push(timedtext.error.details ?? timedtext.error.message)
    }
    if (panel !== null && panel.ok === false) {
      errors.push(`Panel: ${panel.error.details ?? panel.error.message}`)
    }
    if (renderedDom.ok === false) {
      errors.push(`DOM: ${renderedDom.error.details ?? renderedDom.error.message}`)
    }
    collector?.finalize("all_failed")

    throw new TranscriptUnsupportedError(
      "captions_unavailable",
      errors.join("; "),
    )
  },

  async getNativeChapters() {
    return []
  },

  getCurrentTime(env) {
    const currentTime = env.document.querySelector<HTMLVideoElement>("video")?.currentTime
    return Number.isFinite(currentTime) ? currentTime! : 0
  },

  seek(env, seconds) {
    if (!Number.isFinite(seconds)) {
      return false
    }

    const video = env.document.querySelector<HTMLVideoElement>("video")
    if (!video) {
      return false
    }

    video.currentTime = Math.max(0, seconds)
    return true
  },

  buildTimestampUrl(video, seconds) {
    const timestamp = Number.isFinite(seconds) ? Math.max(0, Math.floor(seconds)) : 0
    const url = new URL(buildCanonicalUrl(video.videoId))
    url.searchParams.set("t", String(timestamp))
    return url.toString()
  },
}

function requireIdentity(url: URL): VideoIdentity {
  const identity = youtubeAdapter.getVideoIdentity(url)
  if (!identity) {
    throw new Error("Open a supported YouTube watch page before analyzing.")
  }
  return identity
}

function buildCanonicalUrl(videoId: string): string {
  const url = new URL("https://www.youtube.com/watch")
  url.searchParams.set("v", videoId)
  return url.toString()
}

function normalizeTranscript(
  result: FetchVttSuccess,
  source: TranscriptSource,
): VideoTranscript {
  return {
    segments: normalizeCues(parseVtt(result.rawVtt)),
    language: result.track.languageCode || null,
    source,
    raw: {
      format: "vtt",
      text: result.rawVtt,
      sourceUrl: result.sourceUrl || null,
    },
  }
}

async function runTranscriptStep<T extends FetchVttResult | null>({
  stepName,
  run,
  collector,
  details,
}: {
  stepName: string
  run: () => Promise<T>
  collector: ReturnType<typeof createLogCollector> | null
  details?: string
}): Promise<T | FetchVttFailure> {
  try {
    return collector
      ? await collector.logStep(stepName, run, details)
      : await run()
  } catch (error) {
    return {
      ok: false,
      error: new TranscriptUnsupportedError(
        "transcript_request_failed",
        `${stepName} failed: ${formatThrownError(error)}`,
      ),
    }
  }
}

function formatThrownError(error: unknown): string {
  if (error instanceof Error) return error.message
  if (typeof error === "string") return error
  return "Unknown transcript fallback error"
}

function readText(document: Document, selector: string): string | null {
  const text = document.querySelector<HTMLElement>(selector)?.textContent?.trim()
  return text || null
}

function normalizeDocumentTitle(title: string): string | null {
  const normalized = title.replace(/ - YouTube$/, "").trim()
  return normalized || null
}
