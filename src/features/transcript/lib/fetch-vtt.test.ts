import { describe, expect, it } from "bun:test"

import { buildRawVttUrl, fetchVtt, pickTranscriptTrack } from "./fetch-vtt"
import { parseVtt } from "./parse-vtt"
import type { FetchVttFailure, TranscriptTrack } from "./transcript-schema"

const TRACKS: TranscriptTrack[] = [
  {
    languageCode: "en",
    baseUrl: "https://www.youtube.com/api/timedtext?v=video-1&lang=en",
    name: "English",
  },
  {
    languageCode: "en-US",
    baseUrl: "https://www.youtube.com/api/timedtext?v=video-1&lang=en-US",
    name: "English (US)",
    isAutoGenerated: true,
  },
  {
    languageCode: "de",
    baseUrl: "https://www.youtube.com/api/timedtext?v=video-1&lang=de",
    name: "German",
  },
]

describe("buildRawVttUrl", () => {
  it("adds a VTT format query param", () => {
    expect(
      buildRawVttUrl("https://www.youtube.com/api/timedtext?v=video-1&lang=en"),
    ).toBe("https://www.youtube.com/api/timedtext?v=video-1&lang=en&fmt=vtt")
  })
})

describe("pickTranscriptTrack", () => {
  it("prefers an exact language match", () => {
    expect(pickTranscriptTrack(TRACKS, "de")).toEqual(TRACKS[2])
  })

  it("falls back to a regional language match", () => {
    expect(pickTranscriptTrack(TRACKS, "en-GB")).toEqual(TRACKS[1])
  })
})

describe("fetchVtt", () => {
  it("returns raw VTT for a supported video", async () => {
    const result = await fetchVtt({
      tracks: TRACKS,
      fetchImpl: async (input) => ({
        ok: true,
        status: 200,
        statusText: "OK",
        text: async () => `WEBVTT\n\nNOTE ${input.toString()}`,
      }),
    })

    expect(result.ok).toBe(true)

    if (result.ok) {
      expect(result.rawVtt).toContain("WEBVTT")
      expect(result.sourceUrl).toContain("fmt=vtt")
    }
  })

  it("falls back to JSON3 when VTT returns an empty body", async () => {
    const result = await fetchVtt({
      tracks: TRACKS,
      fetchImpl: async (input) => {
        const url = input.toString()

        if (!url.includes("fmt=")) {
          return {
            ok: true,
            status: 200,
            statusText: "OK",
            text: async () => "",
          }
        }

        if (url.includes("fmt=vtt")) {
          return {
            ok: true,
            status: 200,
            statusText: "OK",
            text: async () => "",
          }
        }

        return {
          ok: true,
          status: 200,
          statusText: "OK",
          text: async () =>
            JSON.stringify({
              events: [
                {
                  tStartMs: 0,
                  dDurationMs: 1750,
                  segs: [{ utf8: "Hello " }, { utf8: "world" }],
                },
              ],
            }),
        }
      },
    })

    expect(result.ok).toBe(true)

    if (result.ok) {
      expect(result.sourceUrl).toContain("fmt=json3")
      expect(parseVtt(result.rawVtt)).toEqual([
        {
          identifier: "1",
          startSec: 0,
          endSec: 1.75,
          text: "Hello world",
        },
      ])
    }
  })

  it("falls back to raw XML timedtext when formatted responses are empty", async () => {
    const result = await fetchVtt({
      tracks: TRACKS,
      fetchImpl: async (input, init) => {
        const url = input.toString()

        if (!url.includes("fmt=")) {
          expect(init?.credentials).toBe("include")

          return {
            ok: true,
            status: 200,
            statusText: "OK",
            text: async () =>
              '<transcript><text start="0.0" dur="1.5">Hello &amp; welcome</text></transcript>',
          }
        }

        return {
          ok: true,
          status: 200,
          statusText: "OK",
          text: async () => "",
        }
      },
    })

    expect(result.ok).toBe(true)

    if (result.ok) {
      expect(result.sourceUrl).toBe(TRACKS[0]?.baseUrl)
      expect(parseVtt(result.rawVtt)).toEqual([
        {
          identifier: "1",
          startSec: 0,
          endSec: 1.5,
          text: "Hello & welcome",
        },
      ])
    }
  })

  it("tries other tracks when the preferred track has no usable transcript", async () => {
    const result = await fetchVtt({
      tracks: [
        {
          languageCode: "en",
          baseUrl: "https://www.youtube.com/api/timedtext?v=video-1&lang=en",
          name: "English",
        },
        {
          languageCode: "ko",
          baseUrl: "https://www.youtube.com/api/timedtext?v=video-1&lang=ko&kind=asr",
          name: "Korean",
          isAutoGenerated: true,
        },
      ],
      fetchImpl: async (input) => {
        const url = input.toString()

        if (url.includes("lang=en")) {
          return {
            ok: true,
            status: 200,
            statusText: "OK",
            text: async () => "",
          }
        }

        if (!url.includes("fmt=json3")) {
          return {
            ok: true,
            status: 200,
            statusText: "OK",
            text: async () => "",
          }
        }

        return {
          ok: true,
          status: 200,
          statusText: "OK",
          text: async () =>
            JSON.stringify({
              events: [
                {
                  tStartMs: 0,
                  dDurationMs: 900,
                  segs: [{ utf8: "안녕하세요" }],
                },
              ],
            }),
        }
      },
    })

    expect(result.ok).toBe(true)

    if (result.ok) {
      expect(result.track.languageCode).toBe("ko")
      expect(result.sourceUrl).toContain("lang=ko")
      expect(result.sourceUrl).toContain("fmt=json3")
      expect(parseVtt(result.rawVtt)).toEqual([
        {
          identifier: "1",
          startSec: 0,
          endSec: 1,
          text: "안녕하세요",
        },
      ])
    }
  })

  it("returns a typed error when captions are unavailable", async () => {
    const result = await fetchVtt({ tracks: [] })

    expect(result.ok).toBe(false)

    if (result.ok) {
      throw new Error("Expected captionless videos to be unsupported")
    }

    const failure = result as FetchVttFailure

    expect(failure.error.reason).toBe("captions_unavailable")
  })
})
