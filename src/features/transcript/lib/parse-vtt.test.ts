import { describe, expect, it } from "bun:test"

import { parseTimestamp, parseVtt } from "./parse-vtt"

describe("parseTimestamp", () => {
  it("parses timestamps with or without an hour segment", () => {
    expect(parseTimestamp("00:01:02.500")).toBe(62.5)
    expect(parseTimestamp("01:02.500")).toBe(62.5)
  })

  it("rejects malformed timestamps", () => {
    expect(() => parseTimestamp("bad-token")).toThrow("Invalid VTT timestamp")
    expect(() => parseTimestamp("00:00:xx")).toThrow("Invalid VTT timestamp")
  })
})

describe("parseVtt", () => {
  it("parses cues with identifiers settings and multiline text", () => {
    const cues = parseVtt(`WEBVTT\n\n1\n00:00:00.000 --> 00:00:02.000 align:start position:0%\nFirst line\nSecond line\n\n00:00:02.500 --> 00:00:05.250 line:90%\nThird line`)

    expect(cues).toEqual([
      {
        identifier: "1",
        startSec: 0,
        endSec: 2,
        text: "First line\nSecond line"
      },
      {
        identifier: undefined,
        startSec: 2.5,
        endSec: 5.25,
        text: "Third line"
      }
    ])
  })

  it("skips NOTE blocks and unrelated text", () => {
    const cues = parseVtt(`WEBVTT\n\nNOTE generated by youtube\nignore this line too\n\nthis is not a cue\n\n00:00:01.000 --> 00:00:03.000\nVisible cue`)

    expect(cues).toEqual([
      {
        identifier: undefined,
        startSec: 1,
        endSec: 3,
        text: "Visible cue"
      }
    ])
  })
})
