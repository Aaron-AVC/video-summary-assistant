import type { TranscriptSegment } from "@/features/platform/types"

export type TranscriptSource =
  | "in_page"
  | "transcript_panel"

export type TranscriptUnsupportedReason =
  | "captions_unavailable"
  | "transcript_request_failed"

export type TranscriptTrack = {
  languageCode: string
  baseUrl: string
  name?: string | null
  kind?: string | null
  isAutoGenerated?: boolean
}

export type InnertubeContext = {
  client?: Record<string, unknown>
  user?: Record<string, unknown>
  request?: Record<string, unknown>
  clickTracking?: Record<string, unknown>
  [key: string]: unknown
}

export type TranscriptPanelBootstrap = {
  endpointUrl: string | null
  params: string | null
  clientName: string | null
  clientVersion: string | null
  visitorData: string | null
  context: InnertubeContext | null
}

export type TranscriptPageMetadata = {
  videoId: string
  title: string | null
  tracks: TranscriptTrack[]
  captionsAvailable: boolean
  transcriptPanel: TranscriptPanelBootstrap | null
}

export type TranscriptCue = TranscriptSegment

export type ParsedVttCue = TranscriptCue & {
  identifier?: string
}

export class TranscriptUnsupportedError extends Error {
  readonly reason: TranscriptUnsupportedReason
  readonly details?: string

  constructor(reason: TranscriptUnsupportedReason, details?: string) {
    const message = details
      ? `${reason}: ${details}`
      : `Transcript unsupported: ${reason}`

    super(message)
    this.name = "TranscriptUnsupportedError"
    this.reason = reason
    this.details = details
  }
}

export type FetchVttSuccess = {
  ok: true
  rawVtt: string
  track: TranscriptTrack
  sourceUrl: string
  source: TranscriptSource
}

export type FetchVttFailure = {
  ok: false
  error: TranscriptUnsupportedError
}

export type FetchVttResult = FetchVttSuccess | FetchVttFailure

export type FetchLike = (
  input: string | URL,
  init?: RequestInit
) => Promise<{
  ok: boolean
  status: number
  statusText: string
  text(): Promise<string>
}>

export type FetchVttOptions = {
  tracks?: TranscriptTrack[] | null
  languageCode?: string
  fetchImpl?: FetchLike
}

export type DownloadTranscriptPayload = {
  filename: string
  rawVtt: string
  mimeType: "text/vtt;charset=utf-8"
}

export type DownloadTranscriptFn = (
  payload: DownloadTranscriptPayload,
) => Promise<void>

export type DownloadTranscriptOptions = {
  rawVtt: string
  videoId: string
  title?: string | null
  downloadImpl?: DownloadTranscriptFn
}
