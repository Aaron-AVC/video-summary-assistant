import type {
  InnertubeContext,
  TranscriptPageMetadata,
  TranscriptPanelBootstrap,
  TranscriptTrack,
} from "@/features/transcript/lib/transcript-schema"

import { extractVideoId } from "./extract-video-id"

type CaptionTrackShape = {
  baseUrl?: string
  languageCode?: string
  kind?: string
  name?: {
    simpleText?: string
    runs?: Array<{
      text?: string
    }>
  }
  vssId?: string
}

type PlayerResponseShape = {
  videoDetails?: {
    title?: string
    videoId?: string
  }
  getTranscriptEndpoint?: {
    params?: string
  }
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: CaptionTrackShape[]
    }
  }
}

type InitialDataShape = {
  engagementPanels?: Array<{
    engagementPanelSectionListRenderer?: {
      panelIdentifier?: string
      content?: {
        continuationItemRenderer?: {
          continuationEndpoint?: {
            getTranscriptEndpoint?: {
              params?: string
            }
          }
        }
      }
    }
  }>
}

export function readPageMetadata(pageUrl: string, html: string): TranscriptPageMetadata {
  const playerResponse = extractPlayerResponse(html)
  const initialData = extractInitialData(html)
  const urlVideoId = extractVideoId(pageUrl)
  const playerVideoId = extractVideoId(playerResponse.videoDetails?.videoId ?? "")
  const videoId = urlVideoId ?? playerVideoId ?? fail("Unable to resolve a canonical YouTube video ID.")
  const playerMetadataMatchesVideo = playerVideoId === videoId
  const title = playerResponse.videoDetails?.title ?? extractTitleFromHtml(html)
  const tracks = playerMetadataMatchesVideo
    ? mapCaptionTracks(playerResponse.captions?.playerCaptionsTracklistRenderer?.captionTracks)
    : []
  const transcriptPanel = playerMetadataMatchesVideo
    ? extractTranscriptPanelBootstrap(html, playerResponse, initialData)
    : null

  return {
    videoId,
    title,
    tracks,
    captionsAvailable: tracks.length > 0,
    transcriptPanel,
  }
}

function extractPlayerResponse(html: string): PlayerResponseShape {
  const json = extractJsonAfterMarker(html, "ytInitialPlayerResponse =")

  return json ? (JSON.parse(json) as PlayerResponseShape) : {}
}

function extractInitialData(html: string): InitialDataShape {
  const json = extractJsonAfterMarker(html, "ytInitialData =")

  return json ? (JSON.parse(json) as InitialDataShape) : {}
}

function extractJsonAfterMarker(html: string, marker: string) {
  const markerIndex = html.indexOf(marker)

  if (markerIndex === -1) {
    return null
  }

  const jsonStart = html.indexOf("{", markerIndex)

  if (jsonStart === -1) {
    return null
  }

  return readJsonObject(html, jsonStart)
}

function readJsonObject(source: string, startIndex: number): string | null {
  let depth = 0
  let inString = false
  let isEscaped = false

  for (let index = startIndex; index < source.length; index += 1) {
    const character = source[index]

    if (!character) {
      break
    }

    if (inString) {
      if (isEscaped) {
        isEscaped = false
        continue
      }

      if (character === "\\") {
        isEscaped = true
        continue
      }

      if (character === '"') {
        inString = false
      }

      continue
    }

    if (character === '"') {
      inString = true
      continue
    }

    if (character === "{") {
      depth += 1
      continue
    }

    if (character === "}") {
      depth -= 1

      if (depth === 0) {
        return source.slice(startIndex, index + 1)
      }
    }
  }

  return null
}

function mapCaptionTracks(captionTracks?: CaptionTrackShape[]): TranscriptTrack[] {
  return (captionTracks ?? [])
    .filter((track): track is Required<Pick<CaptionTrackShape, "baseUrl" | "languageCode">> & CaptionTrackShape =>
      Boolean(track.baseUrl && track.languageCode),
    )
    .map((track) => ({
      baseUrl: track.baseUrl,
      languageCode: track.languageCode,
      kind: track.kind ?? null,
      name: readTrackName(track.name),
      isAutoGenerated: track.kind === "asr" || track.vssId?.startsWith("a.") === true,
    }))
}

function extractTranscriptPanelBootstrap(
  html: string,
  playerResponse: PlayerResponseShape,
  initialData: InitialDataShape,
): TranscriptPanelBootstrap | null {
  const params =
    extractTranscriptParamsFromInitialData(initialData)
    ?? playerResponse.getTranscriptEndpoint?.params
    ?? null
  const apiKey = extractQuotedValue(html, "INNERTUBE_API_KEY")
  const context = extractInnertubeContext(html)

  if (!params && !apiKey && !context) {
    return null
  }

  return {
    endpointUrl: apiKey
      ? `https://www.youtube.com/youtubei/v1/get_transcript?prettyPrint=false&key=${apiKey}`
      : null,
    params,
    clientName: extractNumericValue(html, "INNERTUBE_CONTEXT_CLIENT_NAME"),
    clientVersion: extractQuotedValue(html, "INNERTUBE_CONTEXT_CLIENT_VERSION"),
    visitorData:
      extractQuotedValue(html, "VISITOR_DATA")
      ?? (typeof context?.client?.visitorData === "string" ? context.client.visitorData : null),
    context,
  }
}

function extractTranscriptParamsFromInitialData(initialData: InitialDataShape): string | null {
  for (const panel of initialData.engagementPanels ?? []) {
    const renderer = panel.engagementPanelSectionListRenderer

    if (renderer?.panelIdentifier !== "engagement-panel-searchable-transcript") {
      continue
    }

    return (
      renderer.content?.continuationItemRenderer?.continuationEndpoint?.getTranscriptEndpoint?.params
      ?? null
    )
  }

  return null
}

function extractQuotedValue(html: string, key: string): string | null {
  const match = html.match(new RegExp(`"${key}"\\s*:\\s*"([^"]+)"`))

  return match?.[1] ?? null
}

function extractNumericValue(html: string, key: string): string | null {
  const match = html.match(new RegExp(`"${key}"\\s*:\\s*(\\d+)`))

  return match?.[1] ?? null
}

function extractInnertubeContext(html: string): InnertubeContext | null {
  const marker = '"INNERTUBE_CONTEXT":'
  const markerIndex = html.indexOf(marker)

  if (markerIndex === -1) {
    return null
  }

  const jsonStart = html.indexOf("{", markerIndex)

  if (jsonStart === -1) {
    return null
  }

  const json = readJsonObject(html, jsonStart)

  return json ? (JSON.parse(json) as InnertubeContext) : null
}

function readTrackName(trackName?: CaptionTrackShape["name"]): string | null {
  if (!trackName) {
    return null
  }

  if (trackName.simpleText) {
    return trackName.simpleText
  }

  const text = (trackName.runs ?? [])
    .map((run) => run.text ?? "")
    .join("")
    .trim()

  return text || null
}

function extractTitleFromHtml(html: string): string | null {
  const match = html.match(/<title>(.*?)<\/title>/i)

  return match?.[1]?.replace(/\s*-\s*YouTube$/i, "")?.trim() ?? null
}

function fail(message: string): never {
  throw new Error(message)
}
