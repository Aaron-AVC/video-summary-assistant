import { describe, expect, it } from "bun:test"

import { readPageMetadata } from "./read-page-metadata"
import { extractVideoId } from "./extract-video-id"

const VIDEO_ID = "dQw4w9WgXcQ"

describe("extractVideoId", () => {
  it("normalizes common YouTube URL shapes", () => {
    expect(extractVideoId(`https://www.youtube.com/watch?v=${VIDEO_ID}`)).toBe(VIDEO_ID)
    expect(extractVideoId(`https://youtu.be/${VIDEO_ID}?si=abc`)).toBe(VIDEO_ID)
    expect(extractVideoId(`https://www.youtube.com/shorts/${VIDEO_ID}`)).toBe(VIDEO_ID)
    expect(extractVideoId(`https://www.youtube.com/embed/${VIDEO_ID}`)).toBe(VIDEO_ID)
    expect(extractVideoId(`https://www.youtube.com/live/${VIDEO_ID}`)).toBe(VIDEO_ID)
  })

  it("returns null for invalid video URLs", () => {
    expect(extractVideoId("https://example.com/watch?v=123")).toBe(null)
  })
})

describe("readPageMetadata", () => {
  it("extracts the canonical video ID title and caption tracks", () => {
    const metadata = readPageMetadata(
      `https://www.youtube.com/watch?v=${VIDEO_ID}`,
      `
        <html>
          <head><title>Video Title - YouTube</title></head>
          <body>
            <script>
              ytcfg.set({
                "INNERTUBE_API_KEY": "test-api-key",
                "INNERTUBE_CONTEXT": {
                  "client": {
                    "clientName": "WEB",
                    "clientVersion": "2.20260310.01.00",
                    "visitorData": "visitor-data"
                  }
                },
                "INNERTUBE_CONTEXT_CLIENT_NAME": 1,
                "INNERTUBE_CONTEXT_CLIENT_VERSION": "2.20260310.01.00",
                "VISITOR_DATA": "visitor-data"
              });
              var ytInitialPlayerResponse = {
                "videoDetails": {
                  "videoId": "${VIDEO_ID}",
                  "title": "Video Title"
                },
                "captions": {
                  "playerCaptionsTracklistRenderer": {
                    "captionTracks": [
                      {
                        "baseUrl": "https://www.youtube.com/api/timedtext?v=${VIDEO_ID}&lang=en",
                        "languageCode": "en",
                        "name": { "simpleText": "English" },
                        "vssId": ".en"
                      },
                      {
                        "baseUrl": "https://www.youtube.com/api/timedtext?v=${VIDEO_ID}&lang=en&kind=asr",
                        "languageCode": "en",
                        "kind": "asr",
                        "name": { "simpleText": "English (auto-generated)" },
                        "vssId": "a.en"
                      }
                    ]
                  }
                }
              };
              var ytInitialData = {
                "engagementPanels": [
                  {
                    "engagementPanelSectionListRenderer": {
                      "panelIdentifier": "engagement-panel-searchable-transcript",
                      "content": {
                        "continuationItemRenderer": {
                          "continuationEndpoint": {
                            "getTranscriptEndpoint": {
                              "params": "transcript-params"
                            }
                          }
                        }
                      }
                    }
                  }
                ]
              };
            </script>
          </body>
        </html>
      `,
    )

    expect(metadata).toEqual({
      videoId: VIDEO_ID,
      title: "Video Title",
      captionsAvailable: true,
      tracks: [
        {
          baseUrl: `https://www.youtube.com/api/timedtext?v=${VIDEO_ID}&lang=en`,
          languageCode: "en",
          kind: null,
          name: "English",
          isAutoGenerated: false,
        },
        {
          baseUrl: `https://www.youtube.com/api/timedtext?v=${VIDEO_ID}&lang=en&kind=asr`,
          languageCode: "en",
          kind: "asr",
          name: "English (auto-generated)",
          isAutoGenerated: true,
        },
      ],
      transcriptPanel: {
        endpointUrl: "https://www.youtube.com/youtubei/v1/get_transcript?prettyPrint=false&key=test-api-key",
        params: "transcript-params",
        clientName: "1",
        clientVersion: "2.20260310.01.00",
        visitorData: "visitor-data",
        context: {
          client: {
            clientName: "WEB",
            clientVersion: "2.20260310.01.00",
            visitorData: "visitor-data",
          },
        },
      },
    })
  })

  it("returns a captionless state when no tracks exist", () => {
    const metadata = readPageMetadata(
      `https://www.youtube.com/watch?v=${VIDEO_ID}`,
      `<title>Captionless Video - YouTube</title><script>var ytInitialPlayerResponse = {"videoDetails":{"videoId":"${VIDEO_ID}","title":"Captionless Video"}};</script>`,
    )

    expect(metadata.captionsAvailable).toBe(false)
    expect(metadata.tracks).toEqual([])
    expect(metadata.transcriptPanel).toBeNull()
  })

  it("rejects stale player transcript metadata when the URL identity differs", () => {
    const metadata = readPageMetadata(
      "https://www.youtube.com/watch?v=videoBBBBB2",
      `
        <script>
          var ytInitialPlayerResponse = {
            "videoDetails": { "videoId": "videoAAAAA1", "title": "Stale A" },
            "captions": {
              "playerCaptionsTracklistRenderer": {
                "captionTracks": [{
                  "baseUrl": "https://www.youtube.com/api/timedtext?v=videoAAAAA1&lang=en",
                  "languageCode": "en"
                }]
              }
            },
            "getTranscriptEndpoint": { "params": "stale-panel-params" }
          };
          var ytInitialData = {};
          var ytcfg = {
            "INNERTUBE_API_KEY": "stale-key",
            "INNERTUBE_CONTEXT": { "client": { "clientName": "WEB" } }
          };
        </script>
      `,
    )

    expect(metadata.videoId).toBe("videoBBBBB2")
    expect(metadata.tracks).toEqual([])
    expect(metadata.captionsAvailable).toBe(false)
    expect(metadata.transcriptPanel).toBeNull()
  })
})
